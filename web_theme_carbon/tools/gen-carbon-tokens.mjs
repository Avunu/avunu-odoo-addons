#!/usr/bin/env node
/**
 * Emits the Carbon token layer in the TWO forms Odoo needs, from ONE Dart Sass
 * compilation per theme, so the two can never disagree:
 *
 *   static/lib/carbon/carbon.g10.css          :root { --cds-*: <literal> }   light
 *   static/lib/carbon/carbon.g100.css         :root { --cds-*: <literal> }   dark
 *   static/src/scss/generated/_carbon_tokens.scss       $c-*: <literal>      light
 *   static/src/scss/generated/_carbon_tokens_dark.scss  $c-*: <literal>      dark
 *
 * Why both forms:
 *   - Odoo runs its ~100 !default $o-* variables through Sass colour maths --
 *     darken(), mix(), invert(), and in $o-caret-down literally
 *     str-slice(#{$o-main-text-color}, 2) to build an SVG data-URI. A
 *     var(--cds-*) there yields the string "ar(--cds-text-primary)". So the
 *     bridge needs LITERALS.
 *   - Component CSS wants runtime var(--cds-*) so the dark bundle flips it for
 *     free without duplicating a single rule.
 *
 * The SCSS literals are parsed out of the CSS this same run emits, so the two
 * layers are derived from one source rather than merely audited into agreement.
 *
 * Odoo compiles SCSS with libsass 3.6.6, which has no @use/@forward/sass:*.
 * That is why Carbon is compiled HERE, at build time, and the output committed.
 *
 *   node tools/gen-carbon-tokens.mjs           write (only when bytes change)
 *   node tools/gen-carbon-tokens.mjs --check   compare only, exit 1 if stale
 */
import * as sass from "sass";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const THEMES = [
  { name: "g10", suffix: "", label: "light" },
  { name: "g100", suffix: "_dark", label: "dark" },
];

/* Token families an ERP never renders. Dropping them takes each theme from 533
 * declarations to ~400 and ~22KB to ~17KB. */
const DROP = /^(syntax-|ai-|chat-)/;
const DROP_LINE = /^\s*--cds-(syntax-|ai-|chat-)/;

const entry = (theme) => `
@use "@carbon/styles/scss/config" with (
  $css--reset: false, $css--font-face: false,
  $css--default-type: false, $css--body: false
);
@use "@carbon/styles/scss/theme";
@use "@carbon/styles/scss/themes";
:root { @include theme.theme(themes.$${theme}); }
`;

function compile(theme) {
  return sass.compileString(entry(theme), {
    loadPaths: [path.join(ROOT, "node_modules")],
    style: "expanded",
    charset: false, // Odoo strips @charset anyway; omitting keeps --check stable
    quietDeps: true,
    sourceMap: false,
  }).css;
}

/** Carbon's theme() mixin emits THREE top-level blocks:
 *    1. :root { ... }                        the real token values
 *    2. @media (forced-colors: active) {...} Windows High Contrast overrides
 *                                            (values like SelectedItem/Canvas)
 *    3. :root { ... }                        contextual aliases
 *                                            (--cds-layer: var(--cds-layer-01))
 *
 *  The CSS keeps all three verbatim -- block 2 is an accessibility feature, not
 *  noise. Only block 1 may feed the SCSS literals: a naive whole-file scan lets
 *  the HCM values win and silently ships
 *  `--cds-background-inverse: SelectedItem`, which breaks every tooltip.
 */
function firstRootBlock(css) {
  const open = css.indexOf(":root {");
  const close = css.indexOf("\n}", open);
  return css.slice(open, close);
}

function parseLiterals(css) {
  const out = new Map();
  for (const m of firstRootBlock(css).matchAll(/^\s*--cds-([a-z0-9-]+):\s*([^;]+);/gm)) {
    const value = m[2].trim();
    if (!value.startsWith("var(")) out.set(m[1], value);
  }
  return out;
}

/** Emit the compiled CSS as-is, minus the dropped families, plus our aliases.
 *  Passing Carbon's own output through rather than rebuilding it from parsed
 *  tokens is what keeps blocks 2 and 3 intact. */
function emitCss(css, theme, extraCss = []) {
  const kept = css
    .split("\n")
    .filter((l) => !DROP_LINE.test(l))
    .join("\n")
    .trimEnd();
  return [
    `/* GENERATED by tools/gen-carbon-tokens.mjs -- DO NOT EDIT.`,
    ` * Run \`npm run codegen\` in this module instead.`,
    ` * Carbon theme: ${theme}. Consumed at runtime as var(--cds-*).`,
    ` */`,
    kept,
    ``,
    `:root {`,
    ...extraCss,
    `  /* App-level aliases. Carbon's border-subtle INDEX inverts between`,
    `   * themes -- g10 wants -01 (#e0e0e0), g100 wants -00 (#393939) -- so`,
    `   * every rule reads this one name instead of picking an index. */`,
    `  --carbon-border-subtle: var(--cds-border-subtle-0${theme === "g10" ? 1 : 0});`,
    `  /* A field sits one layer BELOW its container, so a field on a`,
    `   * layer-01 sheet needs field-02 or it is invisible. */`,
    `  --carbon-field-on-layer: var(--cds-field-02);`,
    ``,
    `  /* Carbon ships 10 tag colours and deliberately excludes orange and`,
    `   * yellow. Odoo has 12 colour slots and users pick them semantically, so`,
    `   * collapsing two onto one Carbon colour would make them indistinguishable.`,
    `   * These two are built from the raw ramps, inverted for dark exactly the`,
    `   * way Carbon inverts its own tag tokens (bg and text swap ends). They`,
    `   * cannot be plain $c-* literals: the ramps are theme-INVARIANT, so a tag`,
    `   * built from them would keep a light background on a dark page. */`,
    `  --carbon-tag-background-orange: ${theme === "g10" ? "#ffd9be" : "#8a3800"};`,
    `  --carbon-tag-color-orange:      ${theme === "g10" ? "#8a3800" : "#ffd9be"};`,
    `  --carbon-tag-background-yellow: ${theme === "g10" ? "#fddc69" : "#684e00"};`,
    `  --carbon-tag-color-yellow:      ${theme === "g10" ? "#684e00" : "#fddc69"};`,
    `}`,
    ``,
  ].join("\n");
}

function emitScss(literals, theme, label) {
  // The dark file is spliced into the dark bundle AFTER the light one (both
  // anchor on primary_variables.scss), so it must HARD-ASSIGN. With !default
  // the light values would already be bound and every dark token would be a
  // silent no-op -- the whole dark theme would quietly not apply.
  const dflt = theme === "g10" ? " !default" : "";
  const rows = [];
  for (const [k, v] of literals) {
    if (DROP.test(k)) continue;
    rows.push(`$c-${k}: ${v}${dflt};`);
  }
  return [
    `// GENERATED by tools/gen-carbon-tokens.mjs -- DO NOT EDIT.`,
    `// Run \`npm run codegen\` in this module instead.`,
    `//`,
    `// Carbon theme: ${theme} (${label}).`,
    `// Semantic tokens are parsed from the first :root block of the CSS this`,
    `// same script emits, so the two token layers cannot drift; component,`,
    `// ramp and shell tokens come from @carbon/themes and @carbon/colors.`,
    `//`,
    `// libsass-safe on purpose: literals only, no @use/@forward/sass:*.`,
    `// These feed Odoo's $o-* variables, which get run through darken(), mix(),`,
    `// invert() and str-slice() -- a var(--cds-*) there would break them.`,
    theme === "g10"
      ? `// !default: nothing else declares these, but it keeps them overridable.`
      : `// NO !default: this file must rebind over the light one. See above.`,
    ``,
    `$c-theme-name: "${theme}"${dflt};`,
    ``,
    ...rows,
    ``,
    `// The alias whose Carbon index inverts between themes (see the CSS twin).`,
    `$c-border-subtle: $c-border-subtle-0${theme === "g10" ? 1 : 0}${dflt};`,
    ``,
  ].join("\n");
}

/* ---------------------------------------------------------------------------
 * Carbon's theme() mixin emits only the SEMANTIC tokens. Three more families
 * are needed, each with a different home, and each is sourced from Carbon
 * rather than hand-copied so a Carbon bump cannot leave us stale:
 *
 *   - component tokens (button-*, tag-*) live in @carbon/themes' generated
 *     SCSS as per-theme maps keyed g-10 / g-100;
 *   - the raw IBM Design Language ramps (gray-10..100, blue-*, red-*, ...)
 *     live in @carbon/colors and are what Odoo's $o-gray-* ladder maps onto;
 *   - the UI Shell palette, which Carbon fixes to the dark end in EVERY theme
 *     (a product header stays dark even on a white page).
 * ------------------------------------------------------------------------- */

const THEME_KEY = { g10: "g-10", g100: "g-100" };

/** Read map names straight out of Carbon's generated SCSS, so a release that
 *  adds or renames a component token is picked up instead of silently missed. */
function componentTokenNames(file) {
  const src = fs.readFileSync(
    path.join(ROOT, "node_modules/@carbon/themes/scss/generated", file), "utf8");
  return [...src.matchAll(/^\$([a-z0-9-]+):\s*\(/gm)].map((m) => m[1]);
}

function componentTokens(theme) {
  const files = ["_button-tokens.scss", "_tag-tokens.scss"];
  const uses = [], rows = [];
  files.forEach((f, i) => {
    const mod = f.replace(/^_/, "").replace(/\.scss$/, "");
    uses.push(`@use "@carbon/themes/scss/generated/${mod}" as m${i};`);
    for (const n of componentTokenNames(f)) {
      rows.push(`  --cds-${n}: #{map.get(m${i}.$${n}, "${THEME_KEY[theme]}")};`);
    }
  });
  const css = sass.compileString(
    [`@use "sass:map";`, ...uses, `:root {`, ...rows, `}`].join("\n"),
    { loadPaths: [path.join(ROOT, "node_modules")], quietDeps: true, charset: false }
  ).css;
  return parseLiterals(css);
}

/** Raw ramps from @carbon/colors: Odoo's $o-gray-100..900 ladder remaps onto
 *  these, and the 12 kanban/tag colours come from them too. */
function rawRamps() {
  const colors = require("@carbon/colors");
  const out = new Map();
  for (const [k, v] of Object.entries(colors)) {
    if (!/^[a-z]+\d+$/.test(k) || typeof v !== "string") continue;  // skip *Hover
    out.set(k.replace(/([a-z]+)(\d+)/, "$1-$2"), v);
  }
  for (const k of ["black", "white"]) {
    if (typeof colors[k] === "string") out.set(k, colors[k]);
  }
  return out;
}

/** Carbon's UI Shell is g100 in every theme, so these are IDENTICAL in both
 *  generated files -- which is what keeps the navbar looking the same in
 *  light and dark, as Carbon products do. */
function shellTokens() {
  const c = require("@carbon/colors");
  return new Map([
    ["shell-bg", c.gray100],
    ["shell-border", c.gray80],
    ["shell-text", c.gray10],
    ["shell-text-secondary", c.gray30],
    ["shell-hover", "#353535"],
    ["shell-active", c.gray80],
    ["shell-focus", c.white],
  ]);
}

let stale = false;
function put(rel, content) {
  const abs = path.join(ROOT, rel);
  const prev = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
  if (prev === content) return console.log(`  ok    ${rel}`);
  if (CHECK) {
    stale = true;
    return console.error(`  STALE ${rel}`);
  }
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  // Write only on change: Odoo keys asset bundles off file mtime, so an
  // unconditional write would bust every developer's asset cache each run.
  fs.writeFileSync(abs, content);
  console.log(`  write ${rel}  (${content.length} bytes)`);
}

for (const { name, suffix, label } of THEMES) {
  const css = compile(name);
  const literals = parseLiterals(css);
  const comp = componentTokens(name);
  const ramps = rawRamps();
  const shell = shellTokens();

  // Order matters only for readability; the names are disjoint.
  const scssTokens = new Map([...literals, ...comp, ...ramps, ...shell]);
  console.log(
    `${name}: ${literals.size} semantic + ${comp.size} component + ` +
    `${ramps.size} ramp + ${shell.size} shell = ${scssTokens.size} tokens`);

  // Component tokens also go to CSS so component rules can read them at
  // runtime (tags especially). Ramps and shell stay SCSS-only: they are
  // compile-time inputs to the bridge, not things rules should reach for.
  const extraCss = [...comp].map(([k, v]) => `  --cds-${k}: ${v};`);
  put(`static/lib/carbon/carbon.${name}.css`, emitCss(css, name, extraCss));
  put(`static/src/scss/generated/_carbon_tokens${suffix}.scss`,
      emitScss(scssTokens, name, label));
}

if (stale) {
  console.error("\nGenerated files are out of date. Run `npm run codegen`.");
  process.exit(1);
}
